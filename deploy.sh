#!/bin/bash

# Скрипт для сборки и деплоя MVP приложения

# Цвета для вывода
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
RED='\033[0;31m'
NC='\033[0m' # No Color

echo -e "${YELLOW}Начинаем процесс сборки и деплоя MVP приложения${NC}"

# Шаг 1: Установка зависимостей
echo -e "${YELLOW}Шаг 1: Устанавливаем зависимости...${NC}"
npm install
if [ 0 -ne 0 ]; then
    echo -e "${RED}Ошибка при установке зависимостей${NC}"
    exit 1
fi
echo -e "${GREEN}Зависимости успешно установлены${NC}"

# Шаг 2: Запуск тестов
echo -e "${YELLOW}Шаг 2: Запускаем тесты...${NC}"
npm test -- --watchAll=false
if [ 0 -ne 0 ]; then
    echo -e "${RED}Тесты не прошли${NC}"
    exit 1
fi
echo -e "${GREEN}Тесты успешно пройдены${NC}"

# Шаг 3: Сборка для продакшена
echo -e "${YELLOW}Шаг 3: Собираем приложение для продакшена...${NC}"
npm run build
if [ 0 -ne 0 ]; then
    echo -e "${RED}Ошибка при сборке приложения${NC}"
    exit 1
fi
echo -e "${GREEN}Приложение успешно собрано${NC}"

# Шаг 4: Деплой (здесь можно добавить команды для вашего хостинга)
echo -e "${YELLOW}Шаг 4: Деплой приложения...${NC}"
# Пример команды для деплоя на Netlify
# netlify deploy --prod
# Пример команды для деплоя на GitHub Pages
# npm run deploy
echo -e "${GREEN}Деплой завершен успешно${NC}"

echo -e "${GREEN}MVP приложение успешно собрано и задеплоено!${NC}"
